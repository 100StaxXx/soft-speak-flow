export const DAILY_FORMATION_PRACTICES: readonly DailyFormationPractice[] =
  REVIEWED_FORMATION_PRACTICES.map((practice) => ({
    ...practice,
    source: "reviewed" as const,
    // Formation practices are equally worthy; effort never changes their value.
    xpReward: 10,
    scriptureReference: null,
  }));

export const getDailyFormationPracticeById = (
  practiceId: string,
): DailyFormationPractice | undefined =>
  DAILY_FORMATION_PRACTICES.find((practice) => practice.id === practiceId);

export const getDailyFormationPractice = (date = new Date()): DailyFormationPractice => {
  const dayOfYear = Math.floor(
    (Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) - Date.UTC(date.getFullYear(), 0, 0))
      / 86_400_000,
  );
  return DAILY_FORMATION_PRACTICES[Math.abs(dayOfYear) % DAILY_FORMATION_PRACTICES.length];
};
