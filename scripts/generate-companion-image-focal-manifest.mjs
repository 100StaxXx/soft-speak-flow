#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const PUBLIC_ROOT = path.join(ROOT, "public");
const INITIATE_OUTPUT_ROOT = path.join(ROOT, "output", "companion-initiate-import", "assets");
const OUTPUT_PATH = path.join(ROOT, "src", "generated", "companionImageFocalManifest.ts");
const TARGET_DIRS = [
  {
    dirPath: path.join(PUBLIC_ROOT, "companion-eggs"),
    resolveAssetKey: (filePath) => path.relative(PUBLIC_ROOT, filePath).split(path.sep).join("/"),
  },
  {
    dirPath: path.join(PUBLIC_ROOT, "companion-presets"),
    resolveAssetKey: (filePath) => path.relative(PUBLIC_ROOT, filePath).split(path.sep).join("/"),
  },
  {
    dirPath: path.join(PUBLIC_ROOT, "companion-launcher-away"),
    resolveAssetKey: (filePath) => path.relative(PUBLIC_ROOT, filePath).split(path.sep).join("/"),
  },
  {
    dirPath: INITIATE_OUTPUT_ROOT,
    resolveAssetKey: (filePath) => {
      const relativePath = path.relative(INITIATE_OUTPUT_ROOT, filePath).split(path.sep).join("/");
      return `companion-presets/${relativePath}`;
    },
  },
];

function walk(dirPath) {
  return fs.readdirSync(dirPath, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(dirPath, entry.name);
    if (entry.isDirectory()) return walk(entryPath);
    return [entryPath];
  });
}

function formatNumber(value) {
  return Number.parseFloat(value.toFixed(6));
}

async function getAlphaBounds(imagePath) {
  const { data, info } = await sharp(imagePath)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  let minX = info.width;
  let minY = info.height;
  let maxX = -1;
  let maxY = -1;

  for (let y = 0; y < info.height; y += 1) {
    for (let x = 0; x < info.width; x += 1) {
      const alphaIndex = (y * info.width + x) * info.channels + 3;
      const alpha = data[alphaIndex];
      if (alpha <= 0) continue;
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }

  if (maxX < minX || maxY < minY) {
    return {
      width: info.width,
      height: info.height,
      focalX: 0.5,
      focalY: 0.5,
    };
  }

  return {
    width: info.width,
    height: info.height,
    focalX: formatNumber((minX + maxX + 1) / (2 * info.width)),
    focalY: formatNumber((minY + maxY + 1) / (2 * info.height)),
  };
}

async function buildManifest() {
  const entries = [];

  for (const target of TARGET_DIRS) {
    if (!fs.existsSync(target.dirPath)) continue;

    const files = walk(target.dirPath)
      .filter((filePath) => filePath.endsWith(".png"))
      .sort((left, right) => left.localeCompare(right));

    for (const filePath of files) {
      const bounds = await getAlphaBounds(filePath);
      entries.push([target.resolveAssetKey(filePath), bounds]);
    }
  }

  return Object.fromEntries(entries);
}

function renderManifestFile(manifest) {
  const lines = [
    "/* eslint-disable */",
    "// Generated by scripts/generate-companion-image-focal-manifest.mjs",
    "",
    "export interface BundledCompanionImageFocalManifestEntry {",
    "  focalX: number;",
    "  focalY: number;",
    "  width: number;",
    "  height: number;",
    "}",
    "",
    "export const bundledCompanionImageFocalManifest: Record<string, BundledCompanionImageFocalManifestEntry> = {",
  ];

  for (const [assetKey, bounds] of Object.entries(manifest)) {
    lines.push(
      `  ${JSON.stringify(assetKey)}: { focalX: ${bounds.focalX}, focalY: ${bounds.focalY}, width: ${bounds.width}, height: ${bounds.height} },`,
    );
  }

  lines.push("};", "");
  return `${lines.join("\n")}\n`;
}

async function main() {
  const manifest = await buildManifest();
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, renderManifestFile(manifest), "utf8");
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_PATH)} with ${Object.keys(manifest).length} entries.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack ?? error.message : error);
  process.exit(1);
});
